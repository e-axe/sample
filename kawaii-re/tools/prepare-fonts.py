"""Prepare same-origin WOFF2 fonts with all subsetting performed locally.

Build-time dependencies: fonttools[woff] (FontTools and Brotli).
Only fixed public upstream font and license URLs are downloaded. Page text
and source code are never sent to the font provider.
Run after tools/build.mjs when public copy changes.
"""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "assets" / "fonts"
SOURCES = [
    ("Noto Serif JP", "Kawaii Serif JP", "kawaii-serif-jp", "notoserifjp", "NotoSerifJP"),
    ("Noto Sans JP", "Kawaii Sans JP", "kawaii-sans-jp", "notosansjp", "NotoSansJP"),
]


def download(url, target):
    if not target.exists():
        with urlopen(url, timeout=25) as response:
            target.write_bytes(response.read())


def prepare(source, cache, characters):
    original, alias, stem, directory, filename = source
    source_url = f"https://raw.githubusercontent.com/google/fonts/main/ofl/{directory}/{filename}%5Bwght%5D.ttf"
    license_url = f"https://raw.githubusercontent.com/google/fonts/main/ofl/{directory}/OFL.txt"
    upstream = cache / f"{filename}.ttf"
    license_file = cache / f"{filename}-OFL.txt"
    download(source_url, upstream)
    download(license_url, license_file)
    license_text = license_file.read_text()
    if "SIL OPEN FONT LICENSE Version 1.1" not in license_text:
        raise ValueError(f"Missing official license for {original}")
    font = TTFont(upstream)
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs += [13, 14]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=characters)
    subsetter.subset(font)
    instantiateVariableFont(font, {"wght": (400, 700)}, inplace=True)
    font.flavor = "woff2"
    OUTPUT.mkdir(parents=True, exist_ok=True)
    target = OUTPUT / f"{stem}.woff2"
    font.save(target)
    font.close()
    (OUTPUT / f"{stem}-OFL.txt").write_text(license_text)
    binary = target.read_bytes()
    return f"""@font-face {{
  font-family: '{alias}';
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  src: url('assets/fonts/{stem}.woff2') format('woff2');
}}
""", {
        "family": alias,
        "originalFamily": original,
        "source": source_url,
        "sourceSha256": hashlib.sha256(upstream.read_bytes()).hexdigest(),
        "file": f"assets/fonts/{stem}.woff2",
        "license": f"assets/fonts/{stem}-OFL.txt",
        "licenseSource": license_url,
        "bytes": len(binary),
        "sha256": hashlib.sha256(binary).hexdigest(),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, required=True, help="Local cache for the unmodified upstream TTFs")
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    corpus = (ROOT / "index.html").read_text() + (ROOT / "app.js").read_text()
    characters = "".join(sorted(set(filter(str.isprintable, corpus)) | set(map(chr, range(32, 127)))))
    prepared = [prepare(source, args.cache, characters) for source in SOURCES]
    (ROOT / "fonts.css").write_text(
        "/* Generated by tools/prepare-fonts.py. Locally subset, same-origin Noto fonts. */\n"
        + "\n".join(css for css, _ in prepared)
    )
    (OUTPUT / "manifest.json").write_text(json.dumps({
        "characters": characters,
        "weights": "400..700",
        "fonts": [metadata for _, metadata in prepared],
    }, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"characters": len(characters), "fonts": [metadata for _, metadata in prepared]}, ensure_ascii=False))
