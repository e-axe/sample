const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const sources = ['style.css', 'sky-images.css', 'design-20261012.css'];
function bundle() {
  // Preserve source order, whitespace inside declarations, and relative URL bases.
  return '/* Generated by npm run build:assets. Edit the source CSS files. */\n' + sources.map(file =>
    fs.readFileSync(path.join(root, 'assets/css', file), 'utf8')
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .split('\n').map(line => line.trim()).filter(Boolean).join('\n')
  ).join('\n') + '\n';
}
const target = path.join(root, 'assets/css/site.css');
if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== bundle()) throw new Error('Run npm run build:assets before committing CSS changes.');
  } else fs.writeFileSync(target, bundle());
}
module.exports = { bundle };
